def test_240_seconds_at_24fps_is_5760_frames():
    expect = expect_contract(fps=24, seconds=240)
    assert expect["frames"] == 5760
    assert expect_contract(fps=24, frames=5760)["frames"] == 5760
    # A duration that does not land on a frame boundary is not a contract.
    with pytest.raises(FilmError):
        expect_contract(fps=24, seconds=Fraction(1001, 1000))


