def test_diagnose_build_stores_the_report_and_leaves_bytes_alone(built):
    p, build_id = built
    build_dir = Path(p) / "builds" / build_id
    before = {f: digest(f) for f in build_dir.rglob("*") if f.is_file()}
    lock_path = Path(p) / "manifest/locks.json"
    lock_before = lock_path.read_bytes() if lock_path.is_file() else None
    report = diagnose_build(p, build_id)
    stored = load_report(p, build_id)
    assert stored is not None
    assert stored["findings"] == report["findings"]
    assert {f: digest(f) for f in build_dir.rglob("*") if f.is_file()} \
        == before
    assert (lock_path.read_bytes() if lock_path.is_file() else None) \
        == lock_before


