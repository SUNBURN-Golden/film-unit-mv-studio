def _findings(report, kind=None, severity=None):
    return [f for f in report["findings"]
            if (kind is None or f["kind"] == kind)
            and (severity is None or f["severity"] == severity)]


def _base_expect(**kw):
    return expect_contract(fps=24, seconds=2, audio_streams=1,
                           audio_channels=1, **kw)


