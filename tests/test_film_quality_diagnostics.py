def _ffmpeg(*args):
    subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-y",
                    *[str(a) for a in args]], check=True)


def _clip(target, *, seconds=2, extra_vf=None, audio="sine"):
    """A 320x240/24 testsrc + mono-sine delivery-shaped MP4."""
    video = f"testsrc=size=320x240:rate=24:duration={seconds}"
    cmd = ["-f", "lavfi", "-i", video,
           "-f", "lavfi", "-i",
           f"sine=frequency=440:sample_rate=44100:duration={seconds}"
           + ("," + audio if audio not in ("sine", None) else "")]
    cmd += ["-map", "0:v:0"]
    if audio is not None:
        cmd += ["-map", "1:a:0"]
    if extra_vf:
        cmd += ["-vf", extra_vf]
    cmd += ["-c:v", "libx264", "-pix_fmt", "yuv420p"]
    if audio is not None:
        cmd += ["-c:a", "aac"]
    _ffmpeg(*cmd, target)


def _truncated(source, target, fraction=55):
    """Truncate a +faststart MP4 — the header parses but the decode dies
    mid-file, the honest shape of a damaged delivery."""
    fast = source.with_name(source.stem + "_fs.mp4")
    _ffmpeg("-i", source, "-c", "copy", "-movflags", "+faststart", fast)
    data = fast.read_bytes()
    target.write_bytes(data[:len(data) * fraction // 100])


